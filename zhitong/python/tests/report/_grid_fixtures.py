def two_level_header(*, item: str = "项目名称", group: str = "费用", title: bool = True,
                     pairs: bool = False) -> bytes:
    """评审 (b)：两级表头的审定单，条目列**没有**纵向合并、也没有序号列。

    `item|group` 一行里 group 横跨 B:D（「费用」「工程造价」「结算审核情况」…），下一行才是
    送审金额 | 审定金额 | 核减金额，再下面是数据行与合计行 —— 合计行真读得出金额（判据③的第一道闸拦不住），
    表头首行（第二行）在 A 列是空的：A 列的标题在上一级，所以上一行是表头的一部分，不是抬头。
    `pairs=True`：上一行排两对「项目名称|费用|工期|说明」，走判据①（下面是金额表头）。"""
    wb = Workbook()
    ws = wb.active
    ws.title = "审定单"
    r = 1
    if title:
        ws["A1"] = "结算审定单"
        ws.merge_cells("A1:F1" if pairs else "A1:D1")
        r = 3
    ws[f"A{r}"], ws[f"B{r}"] = item, group
    ws.merge_cells(f"B{r}:D{r}")
    if pairs:
        ws[f"E{r}"], ws[f"F{r}"] = "工期", "说明"
    ws[f"B{r + 1}"], ws[f"C{r + 1}"], ws[f"D{r + 1}"] = "送审金额", "审定金额", "核减金额"
    for i, (name, sub, aud, cut) in enumerate([("土建工程", 8000000, 7200000, 800000),
                                               ("合计", 8000000, 7200000, 800000)], start=r + 2):
        ws[f"A{i}"], ws[f"B{i}"], ws[f"C{i}"], ws[f"D{i}"] = name, sub, aud, cut
    if pairs:
        ws[f"E{r + 2}"], ws[f"F{r + 2}"] = "180天", "无"
    return _save(wb)


