def sheets(spec: dict[str, list[list]]) -> bytes:
    """{表名: 行} → 工作簿（按给定顺序建表）。"""
    wb = Workbook()
    for i, (name, rows) in enumerate(spec.items()):
        ws = wb.active if i == 0 else wb.create_sheet(name)
        ws.title = name
        for row in rows:
            ws.append(row)
    return _save(wb)


